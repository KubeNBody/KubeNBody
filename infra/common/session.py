"""Write configs/<cloud>/session/, the git-ignored per-deployment values of an
overlay (account and project IDs, registries, identities, buckets), from a
JSON spec on stdin:

    {"cloud": "azure", "mode": "real" | "example", "script": "<generator>",
     "images": [{"name": ..., "newName": ..., "app": true | false}],
     "patches": [{"target": {...}, "patch": <object or list>}],
     "secret_store": "<ClusterSecretStore YAML>",
     "env": {"KEY": "value"}}

It writes the kustomize Component (kustomization.yaml, JSON is YAML), the
ClusterSecretStore deploy-k8s.sh applies once the ESO CRDs exist
(cluster-secret-store.yml) and session.env (MODE and the values the Makefile
reads).

NBODY_IMAGE_REGISTRY in the environment (`make configure NBODY_IMAGE_REGISTRY=...`)
points the app images ("app": true) at that registry instead of the cloud's
own, e.g. a registry several clusters share, so the images are built once. Third-party images
keep their mapping. The choice is kept in session.env (IMAGE_REGISTRY), so a
later configure without the variable (make up, make deploy-all) keeps it;
NBODY_IMAGE_REGISTRY=none goes back to the cloud's registry. session.env also
records the app images' registry as APP_REGISTRY, and FORMAT, which
deploy-k8s.sh checks: raise it whenever the configure scripts start writing
something a deploy needs, so a session written before cannot be deployed.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
# 2: the GKE lgtm Service restricted to ADMIN_CIDR, the registry override
FORMAT = 2


def image_registry(session_env: str, mode: str) -> str:
    """The registry override: NBODY_IMAGE_REGISTRY, else the one the previous
    session of the same mode kept, "" for the cloud's own."""
    given = os.environ.get("NBODY_IMAGE_REGISTRY", "").strip().rstrip("/")
    if given:
        return "" if given.lower() == "none" else given
    previous = {}
    if os.path.exists(session_env):
        for line in open(session_env):
            key, sep, value = line.strip().partition("=")
            if sep and not key.startswith("#"):
                previous[key] = value
    return previous.get("IMAGE_REGISTRY", "") if previous.get("MODE") == mode else ""


def main() -> None:
    spec = json.load(sys.stdin)
    out = os.path.join(ROOT, "configs", spec["cloud"], "session")
    os.makedirs(out, exist_ok=True)
    header = (f"# GENERATED by {spec['script']} ({spec['mode']} values): do not edit, not "
              "committed. Re-run `make configure`.\n")
    registry = image_registry(os.path.join(out, "session.env"), spec["mode"])
    images, app_registry = [], ""
    for im in spec["images"]:
        im = dict(im)
        if im.pop("app", False):
            if registry:
                im["newName"] = f"{registry}/{im['name']}"
            app_registry = im["newName"].rsplit("/", 1)[0]
        images.append(im)
    component = {
        "apiVersion": "kustomize.config.k8s.io/v1alpha1",
        "kind": "Component",
        "images": images,
        "patches": [{"target": p["target"],
                     "patch": p["patch"] if isinstance(p["patch"], str) else json.dumps(p["patch"])}
                    for p in spec["patches"]],
    }
    with open(os.path.join(out, "kustomization.yaml"), "w") as f:
        f.write(header + json.dumps(component, indent=2) + "\n")
    with open(os.path.join(out, "cluster-secret-store.yml"), "w") as f:
        f.write(header + spec["secret_store"])
    with open(os.path.join(out, "session.env"), "w") as f:
        env = {**spec["env"], "APP_REGISTRY": app_registry, "IMAGE_REGISTRY": registry}
        f.write(header + f"MODE={spec['mode']}\nFORMAT={FORMAT}\n" + "".join(f"{k}={v}\n" for k, v in env.items()))


if __name__ == "__main__":
    main()
